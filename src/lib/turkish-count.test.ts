import { countPossessive } from './turkish-count';

describe('countPossessive', () => {
  it.each([
    [0, "0'ı"],
    [1, "1'i"],
    [2, "2'si"],
    [3, "3'ü"],
    [4, "4'ü"],
    [5, "5'i"],
    [6, "6'sı"],
    [7, "7'si"],
    [8, "8'i"],
    [9, "9'u"],
    [10, "10'u"],
    [11, "11'i"],
    [12, "12'si"],
    [16, "16'sı"],
    [19, "19'u"],
    [20, "20'si"],
    [30, "30'u"],
    [40, "40'ı"],
    [50, "50'si"],
    [60, "60'ı"],
    [70, "70'i"],
    [80, "80'i"],
    [90, "90'ı"],
    [100, "100'ü"],
    [101, "101'i"],
    [110, "110'u"],
    [1000, "1000'i"],
    [2000, "2000'i"],
    [1_000_000, "1000000'u"],
  ])('%i → %s', (count, text) => {
    expect(countPossessive(count)).toBe(text);
  });
});
